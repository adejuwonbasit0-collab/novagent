def write_files():
    written, skipped_same = 0, 0
    for rel_path, b64_content in FILES_B64.items():
        target = PROJECT_ROOT / rel_path
        new_bytes = base64.b64decode(b64_content)

        if target.exists():
            if target.read_bytes() == new_bytes:
                skipped_same += 1
                continue
            backup_path = BACKUP_DIR / rel_path
            backup_path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(target, backup_path)

        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(new_bytes)
        written += 1
        print("  wrote  " + rel_path)

    print("")
    print(str(written) + " file(s) written, " + str(skipped_same) + " already up to date.")
    if written:
        print("Backups of anything overwritten: " + str(BACKUP_DIR.relative_to(PROJECT_ROOT)))


